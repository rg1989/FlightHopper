// ---- the table ----

const AIRCRAFT = {
  '4A0481': { r: 'YR-ADA', t: 'A320', f: '00', d: 'AIRBUS A-320' },
  '738063': { r: '4X-EKA', t: 'B738', f: '00', d: 'BOEING 737-800' },
  '00830B': { r: 'ZS-HIE', t: 'R44', f: '00', d: 'ROBINSON R-44 Raven' },
  A00018: { r: 'N1AX', t: 'C172', f: '00', d: 'CESSNA 172 Skyhawk' },
  '109866': { r: 'GND', t: 'GND', f: '00', d: '' },
  '106593': { r: 'TWR', t: 'TWR', f: '00', d: '' },
  '3F232B': { r: 'D-LZFN', t: 'SHIP', f: '00', d: 'Zeppelin LZ N07-101' },
  '142635': { r: '09781', t: '', f: '00', d: '' }, // no type: not kept
  '386426': { r: 'F-AZBG', t: 'ZZZZ', f: '00', d: 'SFCA PEYRET TAUPIN TYPE VI' }, // ICAO's "no designator": not kept
  '4B1234': { r: 'HB-XXX', t: 'NEW1', f: '00', d: '' }, // a type types.json does not describe: a type, no category
}
const TYPES = {
  A320: { desc: 'L2J', wtc: 'M' }, B738: { desc: 'L2J', wtc: 'M' }, R44: { desc: 'H1P', wtc: 'L' }, C172: { desc: 'L1P', wtc: 'L' },
  GND: { desc: 'V0-', wtc: '-' }, TWR: { desc: 'T0-', wtc: '-' }, SHIP: { desc: 'B0-', wtc: '-' }, ZZZZ: { desc: '-0-', wtc: '-' },
}
const tableDb = (aircraft: unknown = AIRCRAFT, types: unknown = TYPES): TypeDb => new TypeDb({ userAgent: 't', table: buildTypeTable(aircraft, types) })

test('buildTypeTable: the typed addresses sorted, one type index each; per type its designator and category', () => {
  const t = buildTypeTable(AIRCRAFT, TYPES)
  assert.deepEqual([...t.addrs].map((a) => a.toString(16).padStart(6, '0')), ['00830b', '106593', '109866', '3f232b', '4a0481', '4b1234', '738063', 'a00018'])
  assert.deepEqual([...t.typeOf].map((i) => t.codes[i]), ['R44', 'TWR', 'GND', 'SHIP', 'A320', 'NEW1', 'B738', 'C172'])
  assert.equal(new Set(t.codes).size, t.codes.length, 'each type once')
  assert.equal(t.cats.length, t.codes.length)
})

test('type and category: a hit in either case, a miss, a ~ address and what is no address are null', () => {
  const db = tableDb()
  assert.deepEqual([db.type('4a0481'), db.category('4a0481')], ['A320', 'A3'])
  assert.deepEqual([db.type('4A0481'), db.category('4A0481')], ['A320', 'A3'])
  assert.deepEqual([db.type('738063'), db.type('00830b'), db.type('a00018'), db.type('109866'), db.type('106593'), db.type('3f232b')], ['B738', 'R44', 'C172', 'GND', 'TWR', 'SHIP'])
  assert.deepEqual([db.category('738063'), db.category('00830b'), db.category('a00018'), db.category('109866'), db.category('106593'), db.category('3f232b')], ['A3', 'A7', 'A1', 'C2', 'C3', 'B2'])
  assert.deepEqual([db.type('4b1234'), db.category('4b1234')], ['NEW1', null], 'a type with no description: no category')
  for (const hex of ['ffffff', '000000', '142635', '386426', '~4a0481', '~abc123', '4a048', '4a04811', 'xyzxyz', '', ' 4a0481']) {
    assert.deepEqual([db.type(hex), db.category(hex)], [null, null], JSON.stringify(hex))
  }
  assert.deepEqual([new TypeDb({ userAgent: 't' }).type('4a0481'), new TypeDb({ userAgent: 't' }).category('4a0481')], [null, null], 'no table yet')
})

test('buildTypeTable: what is not an address with a designator is left out; one address twice is kept once; junk is an empty table', () => {
  const t = buildTypeTable({ '4a0481': { t: 'A320' }, '4A0481': { t: 'A20N' }, '73806': { t: 'B738' }, '7380630': { t: 'B738' }, '~abc123': { t: 'B738' }, '738063': { t: 'b738' }, '738064': { t: 'B7380' }, '738065': null, '738066': 'B738', '738067': { t: 7 } }, TYPES)
  assert.deepEqual([...t.addrs], [0x4a0481])
  assert.deepEqual(t.codes.length, 2)
  for (const junk of [null, undefined, 'x', 42, [], [{ t: 'A320' }]]) assert.equal(buildTypeTable(junk, TYPES).addrs.length, 0, JSON.stringify(junk))
  assert.equal(buildTypeTable(AIRCRAFT, null).cats.every((c) => c === 0), true, 'no types.json: types, no categories')
})

// ---- TypeDb: a fake host on a fake clock ----

const zipOf = (aircraft: unknown, types: unknown = TYPES): Uint8Array<ArrayBuffer> =>
  encodeZip([
    { name: 'dbversion.json', data: bytes('{"version":524\n}'), method: 0 },
    { name: 'types.json', data: bytes(JSON.stringify(types)), method: 8 },
    { name: 'aircrafts.json', data: bytes(JSON.stringify(aircraft)), method: 8 },
  ])

type Answer = Response | Error | Promise<Response>
/** A TypeDb on a fake host that gives `first`, then whatever next() sets (a Response is read once: set a new one per call). */
function host(first: Answer) {
  let answer = first
  const calls: { url: string; headers: Headers; signal: AbortSignal | null | undefined }[] = []
  const fetchFn = (async (url: string, init?: RequestInit) => {
    calls.push({ url, headers: new Headers(init?.headers), signal: init?.signal })
    if (answer instanceof Error) throw answer
    return answer
  }) as unknown as typeof fetch
  const clock = { t: Date.UTC(2026, 9, 2, 12) }
  const db = new TypeDb({ userAgent: 'FlightHopper-test', fetchFn, nowMs: () => clock.t })
  return { db, calls, clock, next: (a: Answer) => void (answer = a) }
}
const zipResponse = (aircraft: unknown, etag = '"v1"', types: unknown = TYPES): Response => new Response(zipOf(aircraft, types), { status: 200, headers: { etag } })

test('load: from Mictronics on GitHub, with the user agent and a time limit; the table is in after it', async () => {
  const { db, calls } = host(zipResponse(AIRCRAFT))
  assert.equal(await db.load(), true)
  assert.deepEqual(calls.map((c) => c.url), ['https://raw.githubusercontent.com/Mictronics/aircraft-database/main/indexedDB_old.zip'])
  assert.equal(calls[0].headers.get('user-agent'), 'FlightHopper-test')
  assert.equal(calls[0].headers.get('if-none-match'), null, 'the first is not conditional')
  assert.ok(calls[0].signal instanceof AbortSignal && !calls[0].signal.aborted, 'a stuck download ends by itself')
  assert.deepEqual([db.type('4a0481'), db.category('00830b')], ['A320', 'A7'])
})

test('load: conditional after the first; a 304 keeps the table; a new zip replaces it whole', async () => {
  const { db, calls, next } = host(zipResponse(AIRCRAFT, '"v1"'))
  await db.load()
  next(new Response(null, { status: 304 }))
  assert.equal(await db.load(), true)
  assert.equal(calls[1].headers.get('if-none-match'), '"v1"')
  assert.equal(db.type('4a0481'), 'A320', 'kept')
  next(zipResponse({ '738063': { t: 'B38M' } }, '"v2"'))
  assert.equal(await db.load(), true)
  assert.deepEqual([db.type('738063'), db.type('4a0481')], ['B38M', null], 'the new table only')
  next(new Response(null, { status: 304 }))
  await db.load()
  assert.equal(calls[3].headers.get('if-none-match'), '"v2"')
})

test('load: a failure keeps the old table: a bad status, a network error, a timeout, junk, a zip without the files, JSON that is not, no typed address', async () => {
  const { db, next } = host(zipResponse(AIRCRAFT))
  await db.load()
  const failures: [string, Answer][] = [
    ['500', new Response('Server Error', { status: 500 })],
    ['404', new Response('Not Found', { status: 404 })],
    ['network', new Error('ECONNRESET')],
    ['timeout', new DOMException('The operation was aborted due to timeout', 'TimeoutError')],
    ['html', new Response('<html>rate limited</html>', { status: 200 })],
    ['no aircrafts.json', new Response(encodeZip([{ name: 'types.json', data: bytes('{}'), method: 8 }]), { status: 200 })],
    ['not JSON', new Response(encodeZip([{ name: 'aircrafts.json', data: bytes('{"4A0481":'), method: 8 }, { name: 'types.json', data: bytes('{}'), method: 0 }]), { status: 200 })],
    ['no type in it', zipResponse({ '4A0481': { r: 'YR-ADA', t: '' } })],
  ]
  for (const [what, answer] of failures) {
    next(answer)
    assert.equal(await db.load(), false, what)
    assert.equal(db.type('4a0481'), 'A320', `${what}: the old table stays`)
  }
  const fresh = host(new Error('ECONNREFUSED'))
  assert.equal(await fresh.db.load(), false)
  assert.equal(fresh.db.type('4a0481'), null, 'no table yet, none after')
})

test('load: calls during a download share it', async () => {
  let release!: (r: Response) => void
  const { db, calls } = host(new Promise<Response>((r) => (release = r)))
  const both = Promise.all([db.load(), db.load()])
  release(zipResponse(AIRCRAFT))
  assert.deepEqual(await both, [true, true])
  assert.equal(calls.length, 1)
})

test('tick: loads at once, again a day after a good load, 10 minutes after a failed one, not before', async () => {
  const { db, calls, clock, next } = host(zipResponse(AIRCRAFT))
  await db.tick()
  assert.equal(calls.length, 1, 'the first tick loads')
  clock.t += 24 * HOUR - 1
  await db.tick()
  assert.equal(calls.length, 1, 'a day is not up')
  clock.t += 1
  next(new Error('ECONNRESET'))
  await db.tick()
  assert.equal(calls.length, 2, 'a day on: checked again')
  assert.equal(db.type('4a0481'), 'A320', 'it failed: the table stays')
  clock.t += 10 * MIN - 1
  await db.tick()
  assert.equal(calls.length, 2, 'retried after 10 minutes, not sooner')
  clock.t += 1
  next(new Response(null, { status: 304 }))
  await db.tick()
  assert.equal(calls.length, 3)
  assert.equal(calls[2].headers.get('if-none-match'), '"v1"')
  clock.t += 24 * HOUR - 1
  await db.tick()
  assert.equal(calls.length, 3, 'a 304 is a good load: the next a day on')
})

test('ready: true at once with a table; false after ms without one; true as soon as a load lands; never rejects', async () => {
  assert.equal(await tableDb().ready(5000), true)
  const { db } = host(new Error('ECONNRESET'))
  const t0 = performance.now()
  assert.equal(await db.ready(40), false)
  assert.ok(performance.now() - t0 >= 35, 'it waited')
  await db.load() // fails: the waiting goes on to its end, it does not reject
  assert.equal(await db.ready(20), false)

  let release!: (r: Response) => void
  const gated = host(new Promise<Response>((r) => (release = r)))
  const waits = [gated.db.ready(5000), gated.db.ready(5000)]
  const loading = gated.db.load()
  await sleep(20)
  const t1 = performance.now()
  release(zipResponse(AIRCRAFT))
  assert.deepEqual(await Promise.all(waits), [true, true])
  assert.ok(performance.now() - t1 < 1000, 'not the whole 5 s')
  assert.equal(await loading, true)
})

test('close: the download under way is aborted and fails, the table stays; nothing is asked after it', async () => {
  const signals: AbortSignal[] = []
  const fetchFn = ((_url: string, init?: RequestInit) =>
    new Promise((_resolve, reject) => {
      const signal = init!.signal!
      signals.push(signal)
      signal.addEventListener('abort', () => reject(signal.reason))
    })) as unknown as typeof fetch
  const db = new TypeDb({ userAgent: 't', fetchFn, table: buildTypeTable(AIRCRAFT, TYPES) })
  const pending = db.load()
  assert.equal(signals.length, 1)
  db.close()
  assert.equal(signals[0].aborted, true)
  assert.equal(await pending, false)
  assert.equal(db.type('4a0481'), 'A320')
  assert.equal(await db.load(), false)
  await db.tick()
  assert.equal(signals.length, 1, 'closed: nothing new is asked')
})
