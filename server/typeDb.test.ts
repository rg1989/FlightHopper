test('readZip: stored and deflated entries come back as they were, by name', async () => {
  const types = '{"A320":{"desc":"L2J","wtc":"M"},"B738":{"desc":"L2J","wtc":"M"},"R44":{"desc":"H1P","wtc":"L"}}'
  const zip = encodeZip([
    { name: 'dbversion.json', data: bytes('{"version":524\n}'), method: 0 },
    { name: 'types.json', data: bytes(types), method: 8 },
    { name: 'empty.json', data: new Uint8Array(0), method: 8 },
  ])
  const files = await readZip(zip)
  assert.deepEqual([...files.keys()], ['dbversion.json', 'types.json', 'empty.json'])
  assert.equal(text(files.get('dbversion.json')), '{"version":524\n}')
  assert.equal(text(files.get('types.json')), types)
  assert.equal(files.get('empty.json')?.length, 0)
})

test('readZip: an archive comment after the end record, and a local header with its own extra field', async () => {
  // The real zip ends with "Generated by Mictronics. 27.09.2026 Made available under the Open Data Commons Attribution License."
  const comment = 'Generated by Mictronics. 27.09.2026 Made available under the Open Data Commons Attribution License.'
  const zip = encodeZip([{ name: 'a.json', data: bytes('[1,2,3]'), method: 8, localExtra: 28 }, { name: 'b.json', data: bytes('{}'), method: 0, localExtra: 9 }], comment)
  const files = await readZip(zip)
  assert.equal(text(files.get('a.json')), '[1,2,3]')
  assert.equal(text(files.get('b.json')), '{}')
})

