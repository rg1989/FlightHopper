/** A zip whose second entry claims method 99 in its central directory. */
function zipWithMethod99(): Uint8Array {
  const zip = encodeZip([{ name: 'types.json', data: bytes('{}'), method: 8 }, { name: 'odd.bin', data: bytes('xyz'), method: 0 }])
  const dv = new DataView(zip.buffer)
  let o = zip.length - 22
  o = dv.getUint32(o + 16, true) // the central directory
  o += 46 + dv.getUint16(o + 28, true) // past the first entry
  dv.setUint16(o + 10, 99, true)
  return zip
}

test('readZip: `want` reads only the entries named; the others are skipped unread, a method it cannot read included', async () => {
  const zip = zipWithMethod99()
  assert.deepEqual([...(await readZip(zip, new Set(['types.json']))).keys()], ['types.json'])
  await assert.rejects(readZip(zip), /odd\.bin uses method 99/)
})

test('readZip: what is not a whole, sound zip throws', async () => {
  const good = encodeZip([{ name: 'aircrafts.json', data: bytes('{"4A0481":{"t":"A320"}}'), method: 8 }])
  await assert.rejects(readZip(new Uint8Array(0)), /no end of central directory/)
  await assert.rejects(readZip(bytes('<html><body>404 Not Found</body></html>')), /no end of central directory/)
  await assert.rejects(readZip(good.subarray(0, good.length - 10)), /no end of central directory/, 'the end cut off')
  await assert.rejects(readZip(good.subarray(10)), /no central directory entry/, 'the start cut off: the offsets miss')
  const flipped = good.slice()
  flipped[30 + 'aircrafts.json'.length + 1] ^= 0xff // a byte of the deflated data
  await assert.rejects(readZip(flipped))
  const stored = encodeZip([{ name: 'types.json', data: bytes('{"A320":{}}'), method: 0 }])
  stored[30 + 'types.json'.length + 2] ^= 0x01 // a byte of the stored data: the CRC no longer matches
  await assert.rejects(readZip(stored), /does not match its size or CRC/)
})

